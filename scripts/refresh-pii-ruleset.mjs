#!/usr/bin/env node
/**
 * Regenerate `scripts/pii-tables.json` — the RULE SET of `npm run audit:public-pii`.
 *
 * WHY THIS EXISTS
 *
 * The public-PII gate answers one question: does an UNAUTHENTICATED route hand
 * somebody else's identity to any caller? To answer it, the gate has to know
 * which tables hold other people's rows. It used to know six of them, because
 * six table names were typed into the gate by hand:
 *
 *     profiles, newsletter_subscriptions, federation_owners,
 *     federation_newsletter_subscribers, landing_page_leads, inbound_leads
 *
 * The live schema holds SEVENTY-EIGHT tables with a column that identifies a
 * person (an email address, a phone number, or a person's first/last/full
 * name). A leak in any of the other seventy-two was invisible to the only
 * instrument in this repo that was asking the question — the same defect the
 * RLS rule set suffered in session 57, and the same lesson: **a rule set
 * derived from a hand-written list is only as good as the list, and nothing
 * tells it the list has gone stale.**
 *
 * So the population is now DERIVED from the live schema, by the mechanism:
 * a table holds other people's rows when it has a column that identifies a
 * person. The derivation is the same one the RLS probe uses to learn the
 * schema (the OpenAPI listing the service role can read), so the two rule
 * sets describe the same database.
 *
 * WHAT IS AND IS NOT A PERSONAL COLUMN
 *
 *   email / contact_email / owner_email      an address that reaches a person
 *   phone / phone_number / contact_phone     a number that reaches a person
 *   first_name / last_name / full_name       the parts of a person's name
 *
 * A bare `name` is NOT derived: it is ambiguous. `omni_businesses.name` is a
 * BUSINESS name, and `council_agents.name` is an agent's name, and neither
 * is anybody's identity. The gate keeps a small, explicit overlay for the
 * tables where a bare `name` IS known to be a person's name — a meaning the
 * schema cannot carry, so it has to be written down.
 *
 * FAIL CLOSED
 *
 * If the schema cannot be fetched or the credential is rejected, this exits 2
 * and writes nothing. A rule set regenerated from a failed read is a rule set
 * that describes no database.
 *
 * Usage:
 *   node scripts/refresh-pii-ruleset.mjs           # write scripts/pii-tables.json
 *   node scripts/refresh-pii-ruleset.mjs --print   # print, do not write
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  derivePersonalColumns,
  localSupabase,
  schemaTableNames,
} from "./pii-schema.mjs";

const PRINT_ONLY = process.argv.includes("--print");
const OUT = join(process.cwd(), "scripts", "pii-tables.json");

function fail(message, detail) {
  console.error(`[pii-ruleset] ${message}`);
  if (detail) console.error(`[pii-ruleset]   ${detail}`);
  console.error(
    "[pii-ruleset] The result is UNKNOWN — the rule set was NOT written. Do not read this as a clean result.",
  );
  process.exit(2);
}

/**
 * A column that identifies a PERSON.
 *
 * `name` is deliberately absent: it is a business name as often as a person's,
 * and the schema cannot tell the two apart. The definition lives in
 * `scripts/pii-schema.mjs` so the generator, the drift gate and the gate that
 * applies the rule cannot disagree about what the rule IS.
 */

const env = localSupabase(process.cwd());
const url = env.url;
const serviceKey = env.serviceKey;

if (!url) fail("no Supabase URL in the local env.", "NEXT_PUBLIC_SUPABASE_URL");
if (!serviceKey)
  fail("no service role key in the local env.", "SUPABASE_SERVICE_ROLE_KEY");

const res = await fetch(`${url}/rest/v1/`, {
  headers: {
    apikey: serviceKey,
    Authorization: `Bearer ${serviceKey}`,
    Accept: "application/openapi+json",
  },
});
if (!res.ok) {
  fail(
    `the schema listing could not be fetched (HTTP ${res.status}).`,
    "The service role is required for the OpenAPI listing.",
  );
}
const spec = await res.json();
const defs = spec.definitions || spec.components?.schemas || {};
const tables = schemaTableNames(defs);
if (!tables.length) fail("the schema listing carried no tables.");

/** table -> the personal columns it has. */
const personalColumns = {};
for (const [table, cols] of derivePersonalColumns(defs)) {
  personalColumns[table] = cols;
}

const ruleSet = {
  generatedAt: new Date().toISOString(),
  projectRef: env.projectRef,
  note:
    "The RULE SET of npm run audit:public-pii. Generated by " +
    "npm run refresh:pii-ruleset from the live schema's OpenAPI listing. " +
    "A table is listed here when it has a column that identifies a person " +
    "(an email address, a phone number, or a person's first/last/full name). " +
    "A bare `name` column is NOT personal by derivation -- it is a business " +
    "name as often as a person's -- so the gate carries a small explicit " +
    "overlay for the tables where it is known to be a person's name. " +
    "schemaTables is the whole live table list, so the gate can tell " +
    "'this table holds no personal data' from 'this table does not exist'. " +
    "projectRef is the database this was measured from: the rule set " +
    "describes ONE database, so a gate that finds a different project in " +
    "its own env refuses to answer rather than judge one tree's routes " +
    "against another database's shape.",
  schemaTables: tables,
  personalColumns,
};

const json = JSON.stringify(ruleSet, null, 2) + "\n";

if (PRINT_ONLY) {
  process.stdout.write(json);
} else {
  writeFileSync(OUT, json);
  console.log(
    `[pii-ruleset] wrote ${OUT} — ${tables.length} table(s) in the schema, ` +
      `${Object.keys(personalColumns).length} of them hold a column that identifies a person` +
      (env.projectRef ? ` (project ${env.projectRef})` : "") +
      ".",
  );
}
